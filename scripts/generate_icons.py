def launcher_icons(mark: Image.Image) -> None:
    bbox = visible_bbox(mark)
    center = ((bbox[0] + bbox[2]) / 2, (bbox[1] + bbox[3]) / 2)
    reach = farthest_pixel(mark, *center)
    print(f"mark bbox={bbox} center={center} reach={reach:.1f}px")

    for name, density in DENSITIES.items():
        size = px(ADAPTIVE_DP, density)
        scale = MARK_RADIUS_DP * density / reach
        foreground = place(mark, size, center, scale)
        write_png(foreground, RES / f"mipmap-{name}" / "ic_launcher_foreground.png")
        write_png(silhouette(foreground), RES / f"mipmap-{name}" / "ic_launcher_monochrome.png")

        # Pre-Oreo launchers get the adaptive icon's visible 72dp area in a fixed shape.
        full = Image.new("RGBA", (size, size), (*ICON_BACKGROUND, 255))
        full.alpha_composite(foreground)
        visible = px(72, density)
        offset = (size - visible) // 2
        visible_area = full.crop((offset, offset, offset + visible, offset + visible))
        legacy = px(LEGACY_DP, density)
        inner = px(LEGACY_DP - 4, density)
        body = visible_area.resize((inner, inner), Image.LANCZOS)
        for suffix, shape in (
            ("", lambda d, s: d.rounded_rectangle((0, 0, s - 1, s - 1), radius=s * 0.22, fill=255)),
            ("_round", lambda d, s: d.ellipse((0, 0, s - 1, s - 1), fill=255)),
        ):
            shaped = body.copy()
            shaped.putalpha(smooth_mask(inner, shape))
            icon = Image.new("RGBA", (legacy, legacy), (0, 0, 0, 0))
            icon.alpha_composite(shaped, ((legacy - inner) // 2, (legacy - inner) // 2))
            write_png(icon, RES / f"mipmap-{name}" / f"ic_launcher{suffix}.png")

    anydpi = RES / "mipmap-anydpi-v26"
    anydpi.mkdir(parents=True, exist_ok=True)
    adaptive = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        + GENERATED_NOTICE
        + '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/icon_background" />\n'
        '    <foreground android:drawable="@mipmap/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />\n'
        "</adaptive-icon>\n"
    )
    for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
        (anydpi / name).write_text(adaptive, encoding="utf-8")
        print(f"  {(anydpi / name).relative_to(ROOT)}")


def notification_icon(mark: Image.Image) -> None:
    bbox = visible_bbox(mark)
    center = ((bbox[0] + bbox[2]) / 2, (bbox[1] + bbox[3]) / 2)
    extent = max(bbox[2] - bbox[0], bbox[3] - bbox[1])
    for name, density in DENSITIES.items():
        size = px(NOTIFICATION_DP, density)
        scale = px(NOTIFICATION_CONTENT_DP, density) / extent
        write_png(silhouette(place(mark, size, center, scale)), RES / f"drawable-{name}" / "ic_notification.png")


def splash(logo: Image.Image) -> None:
    logo = logo.convert("RGBA").crop(visible_bbox(logo.convert("RGBA")))
    for name, density in DENSITIES.items():
        width = px(SPLASH_WIDTH_DP, density)
        height = round(logo.height * width / logo.width)
        write_png(logo.resize((width, height), Image.LANCZOS), RES / f"drawable-{name}" / "splash.png")


def flask_from_logo(logo: Image.Image) -> Image.Image:
    """The flask mark on its own, at the logo's resolution and with clean edges.

    The wordmark sits to the right of the flask but the molecule arm reaches over it, so the cut
    is a box rather than a single column. The logo's alpha is binary and its edges were flattened
    onto white first, which leaves a grey fringe; each pixel is matched back to the ink it came
    from and the coverage it had, so the mark scales down sharply instead of muddy."""
    art = logo.convert("RGBA").crop((0, 0, LOGO_FLASK_CUT_X, logo.height))
    pixels = np.array(art).astype(float)
    rgb, alpha = pixels[..., :3], pixels[..., 3]
    ys, xs = np.mgrid[0 : rgb.shape[0], 0 : rgb.shape[1]]
    alpha = np.where((xs > LOGO_FLASK_EDGE_X) & (ys > LOGO_MOLECULE_BOTTOM_Y), 0, alpha)

    white = np.array([255.0, 255.0, 255.0])

    def coverage(ink):
        d = white - np.array(ink, float)
        cov = np.clip(((white - rgb) @ d) / (d @ d), 0.0, 1.0)
        recon = np.array(ink, float) * cov[..., None] + white * (1 - cov)[..., None]
        return cov, np.abs(recon - rgb).sum(-1)

    cov_navy, err_navy = coverage(INK_NAVY)
    cov_teal, err_teal = coverage(INK_TEAL)
    navy = err_navy <= err_teal

    out = np.zeros_like(pixels)
    out[..., :3] = np.where(navy[..., None], INK_NAVY, INK_TEAL)
    out[..., 3] = np.where(navy, cov_navy, cov_teal) * 255 * (alpha > 0)
    mark = Image.fromarray(out.astype("uint8"), "RGBA")
    return mark.crop(visible_bbox(mark))


def resize_premultiplied(image: Image.Image, size: tuple[int, int]) -> Image.Image:
    """Downscale in premultiplied alpha so transparent pixels cannot bleed white into the edges."""
    pixels = np.array(image.convert("RGBA")).astype(float)
    pixels[..., :3] *= pixels[..., 3:4] / 255.0
    small = np.array(Image.fromarray(pixels.astype("uint8"), "RGBA").resize(size, Image.LANCZOS)).astype(float)
    alpha = np.clip(small[..., 3:4], 1e-6, 255)
    small[..., :3] = np.clip(small[..., :3] * 255.0 / alpha, 0, 255)
    return Image.fromarray(small.astype("uint8"), "RGBA")


def wordmark_from_logo(logo: Image.Image) -> Image.Image:
    """The "Chem+" lettering on its own, edges recovered the same way as the flask."""
    art = logo.convert("RGBA")
    pixels = np.array(art).astype(float)
    rgb, alpha = pixels[..., :3], pixels[..., 3]
    ys, xs = np.mgrid[0 : rgb.shape[0], 0 : rgb.shape[1]]
    # The molecule arm reaches over the lettering, so everything above it is dropped.
    alpha = np.where((xs >= LOGO_WORDMARK_X) & (ys > LOGO_WORDMARK_Y), alpha, 0)
    white = np.array([255.0, 255.0, 255.0])
    d = white - np.array(INK_NAVY, float)
    cov = np.clip(((white - rgb) @ d) / (d @ d), 0.0, 1.0)
    out = np.zeros_like(pixels)
    out[..., :3] = INK_NAVY
    out[..., 3] = cov * 255 * (alpha > 0)
    text = Image.fromarray(out.astype("uint8"), "RGBA")
    return text.crop(visible_bbox(text))


def repaint(art: Image.Image, ink) -> Image.Image:
    """Repaint the navy parts of a mark; the teal liquid and the alpha stay as they are."""
    pixels = np.array(art.convert("RGBA")).astype(float)
    rgb = pixels[..., :3]
    teal = (rgb[..., 1] > rgb[..., 0] + 40) & (rgb[..., 2] > rgb[..., 0] + 40)
    pixels[..., :3] = np.where(teal[..., None], rgb, np.array(ink, float))
    return Image.fromarray(pixels.astype("uint8"), "RGBA")


def feature_graphic(mark: Image.Image, logo: Image.Image) -> Image.Image:
    """1024x500 banner: navy ground, the mark in white on the left, wordmark and claims right.

    Play crops this differently across its surfaces, so nothing that matters comes within
    FEATURE_MARGIN of an edge."""
    w, h = 1024, 500
    ys, xs = np.mgrid[0:h, 0:w]
    blend = ((xs / w) * 0.65 + (ys / h) * 0.35)[..., None]
    ground = np.array(FEATURE_DARK) * (1 - blend) + np.array(FEATURE_LIGHT) * blend
    card = Image.fromarray(ground.astype("uint8"), "RGB").convert("RGBA")

    glow = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    ImageDraw.Draw(glow).ellipse((-40, 60, 480, 560), fill=(*INK_TEAL, 60))
    card.alpha_composite(glow.filter(ImageFilter.GaussianBlur(90)))

    # A loose molecule lattice fills the right side without competing with the text.
    lattice = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    draw = ImageDraw.Draw(lattice)
    rng = np.random.default_rng(7)
    nodes = [(int(a), int(b)) for a, b in rng.uniform([560, 40], [1010, 470], size=(14, 2))]
    for i, (x0, y0) in enumerate(nodes):
        for x1, y1 in nodes[i + 1 :]:
            if (x0 - x1) ** 2 + (y0 - y1) ** 2 < 175**2:
                draw.line((x0, y0, x1, y1), fill=(*FEATURE_TEXT, 26), width=2)
    for x0, y0 in nodes:
        draw.ellipse((x0 - 7, y0 - 7, x0 + 7, y0 + 7), fill=(*INK_TEAL, 70))
    card.alpha_composite(lattice)

    flask = resize_premultiplied(repaint(mark, FEATURE_TEXT), _fit(mark, 300))
    card.alpha_composite(flask, (FEATURE_MARGIN + 46, (h - flask.height) // 2))

    text = repaint(wordmark_from_logo(logo), FEATURE_TEXT)
    text = resize_premultiplied(text, _fit(text, 104))
    left = FEATURE_MARGIN + 46 + flask.width + 64
    card.alpha_composite(text, (left, 150))

    draw = ImageDraw.Draw(card)
    draw.text((left + 4, 288), FEATURE_TAGLINE, font=ImageFont.truetype(FONT_REGULAR, 27), fill=FEATURE_MUTED)
    chip_font = ImageFont.truetype(FONT_SEMIBOLD, 22)
    x = left + 4
    for label in FEATURE_CHIPS:
        width = draw.textlength(label, font=chip_font)
        draw.rounded_rectangle((x, 336, x + width + 40, 382), radius=23, outline=(*INK_TEAL, 190), width=2)
        draw.text((x + 20, 359), label, font=chip_font, fill=FEATURE_MUTED, anchor="lm")
        x = int(x + width + 54)
    return card


def _fit(image: Image.Image, height: int) -> tuple[int, int]:
    return round(image.width * height / image.height), height

def reframe_feature_art(art: Image.Image) -> Image.Image:
    """Fit a hand-supplied banner into Play's 1024x500 without letting type reach the edges.

    Play crops this graphic differently across its surfaces, so the art is scaled to
    FEATURE_ART_SCALE and the ground is replicated outwards to fill the rest - on this cream wash
    that reads as padding rather than a border."""
    art = art.convert("RGB")
    width = round(art.height * 1024 / 500)
    left = (art.width - width) // 2
    framed = art.crop((left, 0, left + width, art.height))
    inner_w = round(1024 * FEATURE_ART_SCALE)
    inner_h = round(500 * FEATURE_ART_SCALE)
    inner = np.array(framed.resize((inner_w, inner_h), Image.LANCZOS))
    pad_x, pad_y = (1024 - inner_w) // 2, (500 - inner_h) // 2
    padded = np.pad(
        inner,
        ((pad_y, 500 - inner_h - pad_y), (pad_x, 1024 - inner_w - pad_x), (0, 0)),
        mode="edge",
    )
    return Image.fromarray(padded, "RGB")

def store_images(favicon: Image.Image, logo: Image.Image, backdrop: Image.Image) -> None:
    # Play Store icon: the mark centred on the icon background, 75% of the canvas tall, so it stays
    # clear of the corners Play rounds off. It comes from the logo rather than the favicon: the
    # favicon's mark is smaller, sits left of centre and would have to be scaled up. Flattened to
    # RGB because Play wants a fully opaque PNG.
    # A hand-supplied mark wins over the logo: store/source/icon-mark.png is the flask drawn at a
    # higher resolution with clean edges (transparent background, the two brand inks).
    mark = (
        Image.open(ICON_MARK_SOURCE).convert("RGBA")
        if ICON_MARK_SOURCE.exists()
        else flask_from_logo(logo)
    )
    mark = mark.crop(visible_bbox(mark))
    height = PLAY_ICON_MARK_PX
    width = round(mark.width * height / mark.height)
    icon = Image.new("RGBA", (512, 512), (*ICON_BACKGROUND, 255))
    icon.alpha_composite(resize_premultiplied(mark, (width, height)), ((512 - width) // 2, (512 - height) // 2))
    write_png(icon.convert("RGB"), STORE / "play-icon-512.png")

    # Feature graphic: the banner at the top of the store listing.
    banner = (
        reframe_feature_art(Image.open(FEATURE_ART_SOURCE))
        if FEATURE_ART_SOURCE.exists()
        else feature_graphic(mark, logo)
    )
    write_png(banner.convert("RGB"), STORE / "feature-graphic-1024x500.png")


