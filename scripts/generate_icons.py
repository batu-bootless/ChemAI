def num(value: float) -> str:
    return f"{value:g}"


def to_path_data(tag: str, attrs: dict) -> str:
    if tag == "path":
        return attrs["d"]
    if tag == "line":
        return f"M{num(attrs['x1'])},{num(attrs['y1'])}L{num(attrs['x2'])},{num(attrs['y2'])}"
    if tag == "circle":
        cx, cy, r = attrs["cx"], attrs["cy"], attrs["r"]
        return (
            f"M{num(cx - r)},{num(cy)}"
            f"A{num(r)},{num(r)} 0 1 0 {num(cx + r)},{num(cy)}"
            f"A{num(r)},{num(r)} 0 1 0 {num(cx - r)},{num(cy)}Z"
        )
    if tag == "rect":
        x, y, w, h, r = attrs["x"], attrs["y"], attrs["width"], attrs["height"], attrs.get("rx", 0)
        return (
            f"M{num(x + r)},{num(y)}H{num(x + w - r)}"
            f"A{num(r)},{num(r)} 0 0 1 {num(x + w)},{num(y + r)}V{num(y + h - r)}"
            f"A{num(r)},{num(r)} 0 0 1 {num(x + w - r)},{num(y + h)}H{num(x + r)}"
            f"A{num(r)},{num(r)} 0 0 1 {num(x)},{num(y + h - r)}V{num(y + r)}"
            f"A{num(r)},{num(r)} 0 0 1 {num(x + r)},{num(y)}Z"
        )
    raise ValueError(f"unsupported lucide element: {tag}")


def vector(nodes, color: str, size_dp: int, scale: float, offset: float) -> str:
    paths = "".join(
        f'        <path\n'
        f'            android:pathData="{to_path_data(tag, attrs)}"\n'
        f'            android:strokeWidth="2"\n'
        f'            android:strokeColor="{color}"\n'
        f'            android:strokeLineCap="round"\n'
        f'            android:strokeLineJoin="round" />\n'
        for tag, attrs in nodes
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        + GENERATED_NOTICE
        + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size_dp}dp"\n'
        f'    android:height="{size_dp}dp"\n'
        f'    android:viewportWidth="{size_dp}"\n'
        f'    android:viewportHeight="{size_dp}">\n'
        f'    <group\n'
        f'        android:scaleX="{num(scale)}"\n'
        f'        android:scaleY="{num(scale)}"\n'
        f'        android:translateX="{num(offset)}"\n'
        f'        android:translateY="{num(offset)}">\n'
        f"{paths}"
        "    </group>\n"
        "</vector>\n"
    )


