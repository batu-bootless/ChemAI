# Raster helpers


def px(dp: float, density: float) -> int:
    return int(round(dp * density))


def write_png(image: Image.Image, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path, optimize=True)
    print(f"  {path.relative_to(ROOT)}  {image.size[0]}x{image.size[1]}")


def extract_mark(favicon: Image.Image) -> Image.Image:
    """Cut the flask out of its flat background.

    Alpha grows with the color distance to the background and colors are un-blended, so drawing
    the result over ICON_BACKGROUND gives back the favicon.
    """
    src = favicon.convert("RGB")
    out = Image.new("RGBA", src.size)
    sp, op = src.load(), out.load()
    noise, solid = 4.0, 48.0
    for y in range(src.size[1]):
        for x in range(src.size[0]):
            rgb = sp[x, y]
            dist = math.dist(rgb, ICON_BACKGROUND)
            if dist <= noise:
                op[x, y] = (0, 0, 0, 0)
                continue
            alpha = min(1.0, (dist - noise) / (solid - noise))
            color = tuple(
                max(0, min(255, round(bg + (c - bg) / alpha))) for c, bg in zip(rgb, ICON_BACKGROUND)
            )
            op[x, y] = (*color, round(alpha * 255))
    return out


def visible_bbox(image: Image.Image) -> tuple[int, int, int, int]:
    return image.getchannel("A").point(lambda a: 255 if a > 24 else 0).getbbox()


def farthest_pixel(image: Image.Image, cx: float, cy: float) -> float:
    alpha = image.getchannel("A").load()
    w, h = image.size
    return max(
        math.hypot(x - cx, y - cy) for y in range(h) for x in range(w) if alpha[x, y] > 24
    )


def place(image: Image.Image, size: int, center: tuple[float, float], scale: float) -> Image.Image:
    """Scale `image` and put its point `center` in the middle of a transparent size x size canvas."""
    scaled = image.resize(
        (max(1, round(image.width * scale)), max(1, round(image.height * scale))), Image.LANCZOS
    )
    canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    left = round(size / 2 - center[0] * scale)
    top = round(size / 2 - center[1] * scale)
    # alpha_composite rejects negative destinations, so skip the part that falls off instead.
    canvas.alpha_composite(scaled, (max(0, left), max(0, top)), (max(0, -left), max(0, -top)))
    return canvas


def silhouette(image: Image.Image, color=(255, 255, 255)) -> Image.Image:
    out = Image.new("RGBA", image.size, (*color, 0))
    out.putalpha(image.getchannel("A"))
    return out


def smooth_mask(size: int, draw_shape, supersample: int = 4) -> Image.Image:
    big = Image.new("L", (size * supersample, size * supersample), 0)
    draw_shape(ImageDraw.Draw(big), size * supersample)
    return big.resize((size, size), Image.LANCZOS)


