// Chem+ app: the chemical safety records behind the Safety module.
//
// This is a study and recall aid, not a substitute for a real safety data sheet: the supplier's
// own SDS for the bottle in hand is what governs, because classification varies with purity and
// concentration. The module says so on screen. The data here is the widely agreed GHS
// classification for the common laboratory grade of each substance.
//
// First aid and storage are not written per chemical; they come from the hazard profile, so two
// corrosives cannot end up with contradictory advice. Incompatibilities are tags rather than free
// text so they translate and stay consistent.

