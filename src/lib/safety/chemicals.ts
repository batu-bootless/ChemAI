export interface SafetyChemical {
  id: string;
  name: string;
  nameTr: string;
  formula: string;
  cas: string;
  /** Other names it is looked up by, in either language. */
  synonyms: string[];
  category: SafetyCategory;
  pictograms: PictogramId[];
  signal: "danger" | "warning" | "none";
  /** H-codes; the wording comes from statements.ts. */
  hazards: string[];
  /** P-codes; the wording comes from statements.ts. */
  precautions: string[];
  firstAid: FirstAidProfile;
  storage: StorageProfile;
  incompatible: Incompatibility[];
  /** The one thing worth knowing that the codes do not say. */
  note?: { tr: string; en: string };
}

