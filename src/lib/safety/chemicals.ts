/** Matches name, Turkish name, formula, CAS or any synonym. */
export function searchChemicals(query: string): SafetyChemical[] {
  const q = query.trim().toLocaleLowerCase("tr");
  if (!q) return CHEMICALS;
  return CHEMICALS.filter((chemical) => {
    const haystack = [
      chemical.name,
      chemical.nameTr,
      chemical.formula,
      chemical.cas,
      ...chemical.synonyms,
    ]
      .join(" ")
      .toLocaleLowerCase("tr");
    return haystack.includes(q);
  });
}

export function chemicalById(id: string): SafetyChemical | undefined {
  return CHEMICALS.find((chemical) => chemical.id === id);
}
