const TO_TR = new Map(PAIRS.map(([tr, en]) => [en, tr]));

/** A notebook text (in either language) in the app language. */
export function nb(text: string): string {
  return (getLanguage() === "en" ? TO_EN.get(text) : TO_TR.get(text)) ?? text;
}

